#!/usr/bin/env bash
# Tests of the cloud relay (relay/worker.js) in Cloudflare's local Workers runtime (wrangler dev):
# a simulated phone and agent exercise authentication, forwarding, limits and the agent's decrypt
# command; then the phone's own relay client (core module, JVM) is tested against it.
# Needs Node.js 18+ (wrangler is installed into relay/node_modules on first use).
set -euo pipefail
cd "$(dirname "$0")/.."

PORT="${RELAY_PORT:-18787}"
WORK="$(mktemp -d)"
WRANGLER_PID=""
cleanup() {
  if [ -n "$WRANGLER_PID" ]; then kill "$WRANGLER_PID" > /dev/null 2>&1 || true; fi
  pkill -f "wrangler dev --ip 127.0.0.1 --port $PORT" > /dev/null 2>&1 || true
  pkill -f "workerd serve" > /dev/null 2>&1 || true
  rm -rf "$WORK"
}
trap cleanup EXIT

[ -x relay/node_modules/.bin/wrangler ] || (cd relay && npm ci --no-audit --no-fund > /dev/null)

# A phone key (as the phone's Keystore key would be) and an unknown one.
node -e '
const c = require("crypto"), f = require("fs"), dir = process.argv[1];
const make = () => c.generateKeyPairSync("ec", { namedCurve: "P-256" });
const phone = make(), other = make();
f.writeFileSync(dir + "/key.pem", phone.privateKey.export({ type: "pkcs8", format: "pem" }));
f.writeFileSync(dir + "/key.der", phone.privateKey.export({ type: "pkcs8", format: "der" }));
f.writeFileSync(dir + "/spki.der", phone.publicKey.export({ type: "spki", format: "der" }));
f.writeFileSync(dir + "/other.pem", other.privateKey.export({ type: "pkcs8", format: "pem" }));
' "$WORK"
PIN="sha256/$(openssl dgst -sha256 -binary "$WORK/spki.der" | base64)"

(cd relay && WRANGLER_SEND_METRICS=false exec node_modules/.bin/wrangler dev --ip 127.0.0.1 --port "$PORT" \
  --var "PHONE_PIN:$PIN" --persist-to "$WORK/state" --log-level warn) > "$WORK/wrangler.log" 2>&1 &
WRANGLER_PID=$!
for _ in $(seq 1 90); do
  curl -fsS "http://127.0.0.1:$PORT/" > /dev/null 2>&1 && break
  sleep 1
done
if ! curl -fsS "http://127.0.0.1:$PORT/" > /dev/null 2>&1; then
  cat "$WORK/wrangler.log"
  exit 1
fi

node tools/relay-e2e.mjs "http://127.0.0.1:$PORT" "$WORK"

# The phone's own relay client (core module, as used by the app) and the agent command generated by
# the app's code, against the same relay.
echo "== phone relay client (JVM) with the app's agent command"
mkdir -p "$WORK/sim"
./gradlew -q --console=plain :core:relayPhoneSim --args="http://127.0.0.1:$PORT $WORK $WORK/sim" > "$WORK/sim.log" 2>&1 &
SIM_PID=$!
for _ in $(seq 1 120); do
  [ -f "$WORK/sim/ready" ] && break
  sleep 1
done
fail_sim() {
  echo "FAIL  $1"
  cat "$WORK/sim.log"
  kill "$SIM_PID" > /dev/null 2>&1 || true
  pkill -f RelayPhoneSimKt > /dev/null 2>&1 || true
  exit 1
}
[ -f "$WORK/sim/ready" ] || fail_sim "phone relay client did not connect"
echo "PASS  phone relay client authenticated with its key"
command=$(sed "s#/tmp/#$WORK/sim/#g" "$WORK/sim/command.txt")
bash -c "$command" > "$WORK/sim/out.txt" 2>&1 || fail_sim "agent command: $(cat "$WORK/sim/out.txt")"
cmp -s "$WORK/sim/awc-camera.jpg" "$WORK/sim/picture.jpg" || fail_sim "decrypted picture differs"
echo "PASS  app-generated agent command fetches and decrypts the phone's picture  — $(cat "$WORK/sim/out.txt")"
sleep 2.5
if bash -c "$command" > "$WORK/sim/out2.txt" 2>&1; then fail_sim "the phone's own limit (5 s) was not applied"; fi
grep -q "429" "$WORK/sim/out2.txt" || fail_sim "expected 429: $(cat "$WORK/sim/out2.txt")"
echo "PASS  the phone's own picture limit applies  — 429"
sleep 3
bash -c "$command" > "$WORK/sim/out3.txt" 2>&1 || fail_sim "picture after the limit: $(cat "$WORK/sim/out3.txt")"
echo "PASS  next picture after the limit"
kill "$SIM_PID" > /dev/null 2>&1 || true
pkill -f RelayPhoneSimKt > /dev/null 2>&1 || true
echo "ALL RELAY CHECKS PASSED"
